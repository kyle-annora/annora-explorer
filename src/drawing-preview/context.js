import { DEFAULT_INQUIRY_PROFILE } from '../product-room/inquiry-profile.js';
import { contextForRelease } from '../product-room/release-content.js';
import { createInquiryDraft } from '../product-room/project-domain.js';

/** Build the exact buyer reference from the pinned drawing metadata. A profile
 * needs a complete saved product release; do not attach one to a generic context.
 *
 * createDrawingContext({ drawing, regionId: 'large-bore', modelRevision })
 *
 * `drawing` is content/drawings/linkrods/drawing.json. `modelRevision` comes from
 * the generated model catalog/controller, never from a guessed version string.
 */
export function createDrawingContext({ drawing, regionId, modelRevision }) {
  if (drawing?.modelId !== 'linkrods' || typeof modelRevision !== 'string' || !modelRevision.trim())
    throw new TypeError('The drawing preview needs the connecting rod and its exact prepared model revision.');
  const matches = (drawing.sheets || []).flatMap(sheet => (sheet.regions || [])
    .filter(region => region.id === regionId).map(region => ({ sheet, region })));
  if (matches.length !== 1 || matches[0].region.partId !== 'linkrod-body')
    throw new TypeError('Select an available detail belonging to the connecting rod.');
  const { sheet, region } = matches[0];
  const assetId = drawing.assetId || `${drawing.id}-pdf`;
  const title = 'Connecting rod reference';
  const status = drawing.statusLabel || 'Reference drawing · unreviewed';
  const statusNote = drawing.statusNote || 'Reference drawing only. Manufacturing tolerances and approval have not been supplied.';
  const profile = {
    id: 'drawing-detail-inquiry', version: 'drawing-detail-inquiry-v1',
    fields: DEFAULT_INQUIRY_PROFILE.fields.map(field => ({
      ...field,
      enabled: !['stroke', 'load'].includes(field.id),
      ...(field.id === 'application' ? { label: 'Question or application', hint: 'Describe what needs review. The selected drawing detail stays attached.' } : {}),
      ...(field.id === 'notes' ? { label: 'Requirements to discuss', hint: 'Add required material, tolerances or other details. Nothing is inferred from viewed geometry.' } : {}),
    })),
  };
  const release = {
    id: `drawing-preview:${drawing.id}:${drawing.revision}:${drawing.assetRevision}`,
    productId: drawing.modelId, modelRevision: modelRevision.trim(), version: 1,
    source: 'bundled', createdAt: '2026-11-01T00:00:00.000Z',
    inquiryProfile: profile,
    content: {
      id: drawing.modelId, modelId: drawing.modelId,
      title, shortTitle: 'Connecting rod', eyebrow: '3D / Drawings preview',
      tagline: 'One part. The same drawing reference.',
      description: `${status}. ${statusNote}`,
      summary: 'One CAD solid with two bores and a connecting web. The selected detail links its 3D view to the pinned source drawing.',
      demoNotice: 'Fictional inquiry saved in this browser. Nothing is sent to a manufacturer.',
      roomRevision: 'drawing-preview-room-v1',
      source: {
        label: 'Paired STEP and drawing source', author: 'Open CASCADE SAS; drawing generated by draftwright',
        license: 'LGPL-2.1 with Open CASCADE exception', url: drawing.sourceURL, note: statusNote,
      },
      highlights: [{ label: 'Drawing status', value: status }],
      specGroups: [{ id: 'drawing-reference', title: 'Drawing reference', facts: [
        { label: 'Status', value: status, source: 'Published source drawing and review' },
        { label: 'Source version', value: drawing.revisionLabel || drawing.revision, source: 'Pinned repository snapshot; not a manufacturer-issued revision' },
        { label: 'General tolerance', value: 'Not supplied', source: 'Published source drawing' },
      ] }],
      questions: [],
      documents: [{ id: drawing.id, title: drawing.title, revision: drawing.revision, assetId, description: statusNote, type: 'Reference drawing', nodeId: region.partId }],
      partContent: [{ nodeId: region.partId, title: 'Connecting rod', description: 'A single solid; bore and web selections identify features, not separate components.', documentIds: [drawing.id] }],
    },
  };
  const context = contextForRelease(release, {
    part: { id: region.partId, title: 'Connecting rod' },
    drawing: {
      id: drawing.id, title: drawing.title, revision: drawing.revision, assetId,
      assetRevision: drawing.assetRevision, partId: region.partId,
      sheetId: sheet.id, sheetTitle: sheet.title,
      regionId: region.id, regionLabel: region.label, sourceURL: drawing.sourceURL,
    },
  });
  // Use the same domain validation as the actual reviewed inquiry. This does
  // not save or create a customer record and never fills a required dimension.
  return createInquiryDraft(context, 'drawing-context-validation').context;
}
